inline bool is_known_astrobot_nid(std::string_view nid) {
    // Binary search in sorted NID table
    std::size_t lo = 0, hi = 1746;
    while (lo < hi) {
        std::size_t mid = lo + (hi - lo) / 2;
        if (kAstrobotNids[mid].nid < nid) lo = mid + 1;
        else if (kAstrobotNids[mid].nid > nid) hi = mid;
        else return true;
    }
    return false;
}

